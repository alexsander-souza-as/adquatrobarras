  // Função genérica para configurar qualquer carrossel com botões prev/next
  function setupCarousel(carouselId, prevSelector, nextSelector, itemSelector) {
    const carousel = document.getElementById(carouselId);
    const prevBtn = document.querySelector(prevSelector);
    const nextBtn = document.querySelector(nextSelector);
    if (!carousel || !prevBtn || !nextBtn) return;

    const item = carousel.querySelector(itemSelector);
    if (!item) return;

    const scrollAmount = () => item.offsetWidth + 20;
    prevBtn.addEventListener('click', () => {
      carousel.scrollBy({ left: -scrollAmount(), behavior: 'smooth' });
    });
    nextBtn.addEventListener('click', () => {
      carousel.scrollBy({ left: scrollAmount(), behavior: 'smooth' });
    });
  }

